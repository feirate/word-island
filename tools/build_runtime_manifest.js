import {createHash} from 'node:crypto';
import {readFile,writeFile,readdir} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import path from 'node:path';

const root=fileURLToPath(new URL('../',import.meta.url));
export async function resourceRevisions(base=root) {
  const resources={};
  async function visit(relative) {
    for(const entry of (await readdir(path.join(base,relative),{withFileTypes:true})).sort((a,b)=>a.name.localeCompare(b.name))) {
      const file=path.posix.join(relative,entry.name);
      if(entry.isDirectory())await visit(file);
      else if(/\.(glb|png|jpe?g|webp|svg|m4a|mp3|wav|ogg)$/.test(file))resources[file]=createHash('sha256').update(await readFile(path.join(base,file))).digest('hex');
    }
  }
  await visit('assets');
  return resources;
}

export async function writeRuntimeManifest(base=root,extra={}) {
  const {version}=JSON.parse(await readFile(path.join(root,'package.json'),'utf8'));
  const resources=await resourceRevisions(base);
  for(const file of [...(extra.code||[]),...(extra.shell||[]).filter(file=>file.endsWith('.css'))]) {
    resources[file]=createHash('sha256').update(await readFile(path.join(base,file))).digest('hex');
  }
  const manifest={version,resources,...extra};
  await writeFile(path.join(base,'assets/runtime-manifest.js'),`/* Generated by tools/build_runtime_manifest.js. Content revisions do not follow app versions. */\nself.WORD_ISLAND_RUNTIME=${JSON.stringify(manifest,null,2)};\n`);
  return manifest;
}

if(process.argv[1]&&path.resolve(process.argv[1])===fileURLToPath(import.meta.url))await writeRuntimeManifest();
